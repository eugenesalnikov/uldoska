    <h2>2. Какие данные обрабатываются</h2>
    2.1. Учётные записи на Сайте не создаются.<br>
    2.2. Оператор может обрабатывать следующие персональные данные:<br>
    2.2.1. идентификатор Telegram chat_id;<br>
    2.2.2. имя, username и иные сведения аккаунта Telegram, которые Telegram передаёт Боту при взаимодействии
    пользователя с Ботом;<br>
    2.2.3. номер телефона — только если пользователь добровольно отправил его Боту системным запросом Telegram
    request_contact; в форме объявления на Сайте номер не запрашивается;<br>
    2.2.4. сведения, которые пользователь указывает в объявлении: текст, фотографии, категория, цена, место и иные поля
    формы;<br>
    2.2.5. сведения об откликах, о согласии либо отказе передать контакты, о статусе объявления и о решениях
    модерации;<br>
    2.2.6. токен Ссылки управления объявлением и факт её использования;<br>
    2.2.7. технические данные: IP-адрес, дата и время обращения, данные cookie и аналогичных технологий, тип браузера,
    адрес страницы, с которой выполнен переход, журналы работы сервера и Бота.<br>
    2.3. Оператор не запрашивает паспортные данные, дату рождения, адрес проживания и платёжные реквизиты.<br>
    2.4. Номер телефона не отображается на карточке объявления, в каталоге, в поиске и в иных общедоступных разделах
    Сайта. Номер не передаётся другим пользователям при отклике и не направляется им через Бота.<br>

    <h2>3. Цели обработки</h2>
    3.1. Данные обрабатываются в следующих целях:<br>
    3.1.1. приём, хранение, модерация, публикация, продление и снятие объявлений;<br>
    3.1.2. связь объявления с автором без создания учётной записи;<br>
    3.1.3. направление сервисных сообщений через Бота, включая результат модерации и запрос о передаче контактов;<br>
    3.1.4. обработка откликов и направление сервисных сообщений через Бота без передачи номера телефона другой
    стороне;<br>
    3.1.5. получение и хранение номера телефона, направленного Боту через request_contact, в связи с объявлением;<br>
    3.1.6. соблюдение лимита не более пяти опубликованных объявлений на один идентификатор Telegram;<br>
    3.1.7. обеспечение работы Ссылки управления, содержащей приватный токен;<br>
    3.1.8. защита Сайта от злоупотреблений, расследования нарушений Правил и рассмотрение жалоб;<br>
    3.1.9. исполнение требований закона и ответов на обращения субъектов персональных данных;<br>
    3.1.10. обеспечение работоспособности и безопасности Сайта.<br>
    3.2. Оператор не использует персональные данные для рассылки рекламы без отдельного согласия.<br>

