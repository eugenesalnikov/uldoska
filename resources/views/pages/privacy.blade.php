    нарушаются права субъекта;<br>
    4.1.4. необходимости обработки для исполнения обязанностей, возложенных на Оператора законом.<br>

    <h2>5. Как обрабатываются данные</h2>
    5.1. Оператор осуществляет сбор, запись, систематизацию, накопление, хранение, уточнение, извлечение, использование,
    передачу, блокирование, удаление и уничтожение персональных данных.<br>
    5.2. Обработка выполняется с использованием средств автоматизации.<br>
    5.3. Номер телефона обрабатывается только после того, как пользователь в Боте подтвердил отправку контакта через
    request_contact. Подача объявления на Сайте сама по себе номер не создаёт.<br>
    5.4. Оператор не передаёт номер телефона автора отправителю отклика и не показывает его на карточке объявления.
    Номер хранится в связи с объявлением как служебные данные.<br>
    5.5. Направляя отклик, пользователь соглашается на передачу автору объявления сведений, необходимых для обработки
    отклика, включая идентификатор Telegram.<br>
    5.6. Ссылка управления даёт доступ к объявлению любому лицу, которое ею воспользуется. Оператор не отвечает за
    передачу ссылки третьим лицам самим автором.<br>

    <h2>6. Кто может получить данные</h2>
    6.1. Оператор не продаёт персональные данные.<br>
    6.2. Данные могут стать известны:<br>
    6.2.1. автору объявления и отправителю отклика — идентификатор Telegram и иные сведения, технически нужные, чтобы
    обработать отклик через Бота. Номер телефона в этот обмен не входит;<br>
    6.2.2. лицу, которому автор передал Ссылку управления;<br>
    6.2.3. лицам, привлекаемым Оператором для размещения инфраструктуры Сайта: хостинг-провайдеру, регистратору домена,
    оператору электронной почты, при условии, что им доступен только необходимый объём данных;<br>
    6.2.4. мессенджеру Telegram, поскольку Бот работает на инфраструктуре Telegram;<br>
    6.2.5. государственным органам — в случаях и порядке, предусмотренных законом.<br>
    6.3. Telegram является независимым сервисом. Обработка данных в Telegram осуществляется в соответствии с правилами и
    политикой конфиденциальности Telegram. Оператор не контролирует инфраструктуру Telegram.<br>
    6.4. Используя Бота, пользователь понимает, что часть сведений передаётся в Telegram и может обрабатываться за
    пределами Российской Федерации. Продолжая использование Бота, пользователь даёт согласие на такую передачу в объёме,
    необходимом для работы Бота.<br>

    <h2>7. Сроки хранения</h2>
    7.1. Данные объявления хранятся в течение срока его размещения, а после снятия, отклонения, истечения срока либо
    удаления — в течение срока, необходимого для повторной публикации, разбора жалоб, защиты прав Оператора и исполнения
    закона, но не дольше 3 (трёх) лет, если иной срок не установлен законом или обращением субъекта.<br>
    7.2. Идентификатор Telegram, связанный с объявлением, хранится столько же, сколько хранится соответствующее
    объявление и связанные с ним обращения.<br>
    7.3. Привязанный номер телефона хранится, пока сохраняется связь номера с объявлением либо с идентификатором
    Telegram и пока это нужно для целей, указанных в разделе 3. После отзыва согласия либо удаления объявления номер
    уничтожается или обезличивается в разумный срок, если закон не требует более длительного хранения.<br>
    7.4. Журналы сервера и технические логи хранятся не дольше 12 (двенадцати) месяцев, если иное не требуется для
    расследования инцидента.<br>
    7.5. Оператор вправе удалить данные ранее указанных сроков при прекращении работы Сайта либо при отсутствии
    необходимости в обработке.<br>

