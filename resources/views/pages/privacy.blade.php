    <h2>1. Общие положения</h2>
    1.1. Настоящая Политика обработки персональных данных (далее — Политика) определяет порядок и условия обработки
    персональных данных пользователей сайта https://uldoska.ru (далее — Сайт).<br>
    1.2. Оператор персональных данных — лицо, осуществляющее функционирование Сайта (далее — Оператор). Запросы
    субъектов персональных данных направляются на адрес: support@uldoska.ru.<br>
    1.3. Сайт является информационным сервисом размещения объявлений. Официальный чат-бот Сайта: @uldoska_bot,
    https://t.me/uldoska_bot (далее — Бот).<br>
    1.4. Политика разработана во исполнение Федерального закона от 27.07.2006 № 152-ФЗ «О персональных данных».<br>
    1.5. Используя Сайт и (или) Бота, субъект персональных данных подтверждает, что ознакомился с Политикой. Если
    субъект не согласен с Политикой, он обязан прекратить использование Сайта и Бота.<br>
    1.6. Действующая редакция Политики доступна по адресу: https://uldoska.ru/privacy.<br>
    1.7. Оператор вправе изменять Политику. Новая редакция вступает в силу с момента публикации по адресу, указанному в
